"""Writes the algebra word problems for the Rust calculator: rust_calculator/src/ops/words_data.rs src/word_layouts.rs and tests/words_expected.tsv (what Python answers with each problem's own numbers).

    python operator_keys/make_rust_words.py

words_data.rs : ITEMS    - all 1,000 problems (category, id, text, Ready or Reference, key)
                SPECS    - for the 377 Ready ones: the text template, its numbers as written, which solver answers it, the place of each box's number, the boxes' starting numbers
                OPERATORS - one Operator per Ready problem (key "word:age/0002"), computed by the hand-written src/ops/words.rs
word_layouts.rs: how each Ready problem's row is drawn (its equation as cards), the same cards the Python row files hold.

The Python files are the source of truth (operator_row_math_for_algebra_word_problems, operators_one_algebra_word_problem_per_file).  Run again whenever they change.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import algebra_word_problem_catalog as catalog  # noqa: E402
import operator_row_math_for_algebra_word_problems as W  # noqa: E402
import operators_one_algebra_word_problem_per_file as P  # noqa: E402
from operator_row_math import row_tree  # noqa: E402
from make_rust_layouts import KIND, PART, rs  # noqa: E402  (operator_keys is on the path when run from there)

DATA = os.path.join(ROOT, "rust_calculator", "src", "ops", "words_data.rs")
LAYOUTS = os.path.join(ROOT, "rust_calculator", "src", "word_layouts.rs")
EXPECTED = os.path.join(ROOT, "rust_calculator", "tests", "words_expected.tsv")


def strs(items):
    return "&[" + ", ".join(rs(str(x)) for x in items) + "]"


def layout_line(key, m):
    smap = row_tree.slot_map(m)
    levels = list(getattr(m, "LEVELS", None) or [0] * len(m.LEFT))
    fracs = list(getattr(m, "FRAC", None) or [[] for _ in m.LEFT])
    cards, b = [], 0
    for n, (kind, text) in enumerate(m.LEFT):
        slot = -1
        if kind == "box":
            slot = smap[b]
            b += 1
        frac = fracs[n] if n < len(fracs) else []
        fr = "&[" + ", ".join("(%d, %d)" % (g, PART[p]) for g, p in frac) + "]" if frac else "N"
        cards.append("card(%s, %s, %d, %d, %s)" % (KIND[kind], rs(text), slot, levels[n], fr))
    return "    Layout { key: %s, right_box: %s, cards: &[%s] }," % (rs(key), "true" if m.RIGHT else "false", ", ".join(cards))


def main():
    items = catalog.load_catalog(os.path.join(ROOT, "operators_one_algebra_word_problem_per_file", "INDEX.md"))
    data = [
        "// @generated by operator_keys/make_rust_words.py from the Python word-problem files - do not edit by hand.",
        "use super::words::{Item, Spec};",
        "use crate::operator::{CalcKind, Operator};",
        "use crate::value::Value;",
        "",
        "fn needs_typed_input(_: &[f64]) -> Result<Value, String> {",
        '    Err("this algebra word problem is computed from typed values".into())',
        "}",
        "",
        "pub static ITEMS: &[Item] = &[",
    ]
    for it in items:
        data.append("    Item { key: %s, category: %s, id: %s, problem: %s, ready: %s }," % (
            rs(it["key"]), rs(it["category"]), rs(it["id"]), rs(it["problem"]), "true" if it["status"] == "Ready" else "false"))
    data += ["];", "", "pub static SPECS: &[Spec] = &["]
    ops = []
    layouts = []
    expected = []
    index = 0
    for it in items:
        if it["status"] != "Ready":
            continue
        problem = P.get(it["key"])
        mod = W.get(it["key"])
        assert mod.CALC == "ready", it["key"]
        assert len(mod.INPUTS) == len(mod.BOX_INDEX) == len(mod.DEFAULTS), it["key"]
        solver = problem.SOLVER
        assert solver in ("word_solver", "number_puzzle"), (it["key"], solver)
        data.append("    Spec { template: %s, numbers: %s, solver: %s, box_index: &[%s], defaults: %s }," % (
            rs(problem.TEMPLATE), strs(problem.NUMBERS), rs(solver), ", ".join(str(i) for i in mod.BOX_INDEX), strs(mod.DEFAULTS)))
        ops.append("""    Operator {
        key: %s,
        name: %s,
        symbol: "",
        category: "Algebra word problems",
        subcategory: %s,
        formula: %s,
        pattern: %s,
        inputs: %s,
        calc: CalcKind::Ready,
        extra: &[],
        variadic: false,
        kinds: &[],
        compute: needs_typed_input,
        compute_v: Some(|a| super::words::run(%d, a)),
    },""" % (rs("word:" + it["key"]), rs(mod.NAME), rs(it["category"]), rs(it["problem"]), rs(mod.PATTERN), strs(mod.INPUTS), index))
        layouts.append(layout_line("word:" + it["key"], mod))
        answer = problem.compute()
        expected.append("word:%s\t%s" % (it["key"], " ".join(repr(float(v)) for v in (answer if isinstance(answer, list) else [answer]))))
        index += 1
    data += ["];", "", "pub static OPERATORS: &[Operator] = &["] + ops + ["];", ""]
    open(DATA, "w", encoding="utf-8", newline="\n").write("\n".join(data))
    open(EXPECTED, "w", encoding="utf-8", newline="\n").write("\n".join(expected) + "\n")
    head = [
        "//! GENERATED by operator_keys/make_rust_words.py from the Python row files: do not edit by hand.",
        "//! How each Ready algebra word problem's row is drawn: its equation written as cards (see layout.rs).",
        "",
        "use crate::layout::{card, Layout, B, D, N, O, U};",
        "",
        "pub static WORD_LAYOUTS: &[Layout] = &[",
    ]
    open(LAYOUTS, "w", encoding="utf-8", newline="\n").write("\n".join(head + layouts + ["];", ""]))
    print("wrote %d problems (%d ready) -> %s, %s" % (len(items), index, os.path.relpath(DATA, ROOT), os.path.relpath(LAYOUTS, ROOT)))


if __name__ == "__main__":
    main()
