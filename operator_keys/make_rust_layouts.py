"""Writes rust_calculator/src/layouts.rs: how every operator's row is drawn (its picture as cards), read from the Python row files.

    python operator_keys/make_rust_layouts.py

The Python row files (operator_row_math/<area>/<group>/<operator>/<operator>.py, themselves written by make_operator_row_files.py from operator_row_specs.txt) are the
source of truth.  For every operator this copies, card by card: the kind (op / box / out / dec), the text, which input a box shows (SLOTS), the grid row of a card (LEVELS:
-1 = an exponent, +1 = a subscript), and the fractions the card is inside (FRAC).  Run it again whenever the row files change.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import operator_row_math as R  # noqa: E402
from operator_row_math import row_tree  # noqa: E402

OUT = os.path.join(ROOT, "rust_calculator", "src", "layouts.rs")
KIND = {"op": "O", "box": "B", "out": "U", "dec": "D"}
PART = {"n": 0, "d": 1, "bar": 2, "hide": 3}


def rs(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build_text():
    lines = [
        "//! GENERATED by operator_keys/make_rust_layouts.py from the Python row files: do not edit by hand.",
        "//! How each operator's row is drawn: its picture written as cards (see layout.rs and the README's design rules).",
        "",
        "use crate::layout::{card, Layout, B, D, N, O, U};",
        "",
        "pub static LAYOUTS: &[Layout] = &[",
    ]
    count = 0
    for key in R.keys():
        m = R.get(key)
        smap = row_tree.slot_map(m)
        levels = list(getattr(m, "LEVELS", None) or [0] * len(m.LEFT))
        fracs = list(getattr(m, "FRAC", None) or [[] for _ in m.LEFT])
        cards, b = [], 0
        for n, (kind, text) in enumerate(m.LEFT):
            slot = -1
            if kind == "box":
                slot = smap[b]
                b += 1
            frac = fracs[n] if n < len(fracs) else []
            if frac:
                fr = "&[" + ", ".join("(%d, %d)" % (g, PART[p]) for g, p in frac) + "]"
            else:
                fr = "N"
            cards.append("card(%s, %s, %d, %d, %s)" % (KIND[kind], rs(text), slot, levels[n], fr))
        lines.append("    Layout { key: %s, right_box: %s, cards: &[%s] }," % (rs(key), "true" if m.RIGHT else "false", ", ".join(cards)))
        count += 1
    lines.append("];")
    lines.append("")
    return "\n".join(lines), count


def main():
    text, count = build_text()
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote %s: %d layouts" % (os.path.relpath(OUT, ROOT), count))


if __name__ == "__main__":
    main()
