"""Write rust_calculator/src/ops/generated.rs from the operator catalog.

Run from the project root (after make_operator_keys.py):   python operator_keys/make_rust_ops.py

For every operator that
  - is NOT already written by hand in src/ops/mod.rs, and
  - is Reference (formula only), or is Ready and has a function named after its folder in the Rust file
    for its group (src/ops/physics.rs, geometry.rs, math.rs ...),
one `Operator { ... }` entry is generated from the catalog (key, name, symbol, formula, pattern, inputs, optional
constants with their defaults).  Only the compute bodies are written by hand.
Ready operators with no Rust function yet are listed at the end so you can see what is left.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OPS = os.path.join(ROOT, "rust_calculator", "src", "ops")
MODULES = {"physics": "physics", "geometry": "geometry", "math": "math"}   # key group -> Rust file (module)


def rs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def fnum(x):
    s = repr(float(x))
    return s if ("e" in s or "." in s or "inf" in s) else s + ".0"


def main():
    cat = json.load(open(os.path.join(ROOT, "operator_keys", "operator_keys.json"), encoding="utf-8"))["operators"]
    handwritten = set(re.findall(r'key: "([^"]+)"', open(os.path.join(OPS, "mod.rs"), encoding="utf-8").read()))
    fns = {}
    for group, mod in MODULES.items():
        path = os.path.join(OPS, mod + ".rs")
        fns[group] = set(re.findall(r"^pub fn (\w+)\(", open(path, encoding="utf-8").read(), re.M)) if os.path.exists(path) else set()

    out = ["// @generated by operator_keys/make_rust_ops.py - do not edit by hand (edit the catalog or the compute functions).",
           "use super::{geometry, math, physics};",
           "use crate::operator::{CalcKind, Operator};",
           "use crate::value::Value;", "",
           'fn reference_only(_: &[f64]) -> Result<Value, String> {',
           '    Err("this operator is reference-only (no calculation yet)".into())', "}", "",
           "pub const GENERATED: &[Operator] = &["]
    done = ref = 0
    todo = []
    for x in cat:
        key = x["key"]
        if key in handwritten:
            continue
        group = key.split("/")[0]
        leaf = key.rsplit("/", 1)[1]
        if x["status"] == "Reference":
            calc, comp, extra = "Reference", "reference_only", []
        else:
            numeric = x["input_kinds"] and set(x["input_kinds"]) == {"number"} or not x["inputs"]
            if numeric and leaf in fns.get(group, set()):
                calc, comp = "Ready", "%s::%s" % (MODULES[group], leaf)
                extra = [(p["name"], p["default"]) for p in x["compute_params"]
                         if p["kind"] == "optional" and isinstance(p.get("default"), (int, float))]
                opt = [p for p in x["compute_params"] if p["kind"] == "optional"]
                assert len(opt) == len(extra), "non-numeric default in %s" % key
            else:
                todo.append(key)
                continue
        done += calc == "Ready"
        ref += calc == "Reference"
        out += ["    Operator {",
                "        key: %s," % rs(key), "        name: %s," % rs(x["name"]), "        symbol: %s," % rs(x["symbol"]),
                "        category: %s," % rs(x["category"]), "        subcategory: %s," % rs(x["subcategory"]),
                "        formula: %s," % rs(x["formula"]), "        pattern: %s," % rs(x.get("pattern") or x["formula"]),
                "        inputs: &[%s]," % ", ".join(rs(i) for i in x["inputs"]),
                "        calc: CalcKind::%s," % calc,
                "        extra: &[%s]," % ", ".join("(%s, %s)" % (rs(n), fnum(v)) for n, v in extra),
                "        variadic: false,", "        compute: %s," % comp, "    },"]
    out.append("];")
    open(os.path.join(OPS, "generated.rs"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("generated: %d ready operators, %d reference operators (hand-written in mod.rs: %d)" % (done, ref, len(handwritten)))
    print("Ready operators still without a Rust function: %d" % len(todo))
    json.dump(todo, open(os.path.join(ROOT, "operator_keys", "rust_todo.json"), "w", encoding="utf-8"), indent=1)


if __name__ == "__main__":
    main()
