"""The Navier-Stokes equations as the calculator's rows and columns.   Nothing here is wired into the calculator.

    python navier-stokes/make_navier_stokes_rows.py            # writes navier_stokes_rows.jpg, navier_stokes_rows.txt and navier_stokes_rows_data.py
    python navier-stokes/make_navier_stokes_rows.py --preview  # opens the five rows as the calculator's own row widget draws them

Each equation is ONE calculator row (the equation of one direction).  In a row every symbol is its own CARD in its own COLUMN, and a card also has a GRID ROW:
a fraction has its numerator on the grid row above its bar and its denominator on the grid row below; an exponent is one grid row up, a subscript one down.
Those grid rows belong to the one calculator row.  They are not Row 2, Row 3 ...

The cards, levels and fraction groups come from the project's own code (make_operator_row_files.build, layout.group_fractions) and the places of the cards from
the row planner (row_builder._plan), so this is exactly what an operator row file with these equations would hold.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "operator_keys"))
import make_operator_row_files as MK  # noqa: E402
from operator_row_math.row_builder import _plan  # noqa: E402

# One spec line per equation, in the language of operator_keys/operator_row_specs.txt: a space between cards, ² is an exponent card, ₓ a subscript card.
VECTOR = "ρ ( ∂ u / ∂ t + ( u · ∇ ) u ) = − ∇ p + μ ∇ ² u + f"
CONTINUITY = "∂ u / ∂ x + ∂ v / ∂ y + ∂ w / ∂ z = 0"


def component(q, axis):
    f_card = "f ₓ"          # the subscript card; build_all() puts the real letter (x, y or z) on it, one grid row down
    return ("ρ ( ∂ {q} / ∂ t + u ∂ {q} / ∂ x + v ∂ {q} / ∂ y + w ∂ {q} / ∂ z ) = − ∂ p / ∂ {a} "
            "+ μ ( ∂ ² {q} / ∂ x ² + ∂ ² {q} / ∂ y ² + ∂ ² {q} / ∂ z ² ) + {f}").format(q=q, a=axis, f=f_card), axis


ROWS = [
    ("Vector form", VECTOR),
    ("x direction (u)", component("u", "x")),
    ("y direction (v)", component("v", "y")),
    ("z direction (w)", component("w", "z")),
    ("Continuity", CONTINUITY),
]


def build_all():
    out = []
    for title, spec in ROWS:
        dsl, letter = spec if isinstance(spec, tuple) else (spec, None)
        left, right, slots, pattern, levels, fracs = MK.build("navier_stokes/" + title, dsl, [], "reference")
        if letter:
            left[-1] = ("op", letter)          # the force component: f with its direction letter one grid row down
        placed, bars, end = _plan(len(left), levels, fracs)
        out.append({"title": title, "dsl": dsl, "LEFT": left, "LEVELS": levels, "FRAC": fracs, "placed": placed, "bars": bars, "columns": end})
    return out


def role(fr):
    return "" if not fr else {"n": "numerator", "d": "denominator", "bar": "bar (the / card, not drawn)", "hide": "hidden bracket"}[fr[-1][1]]


def write_text(rows):
    lines = ["The Navier-Stokes equations as calculator rows: one equation = ONE row.", "",
             "card = one symbol, its own column.  grid row: 0 = the line (the bar, = + ...), -1 = one up (numerator or exponent), +1 = one down (denominator or subscript).", ""]
    for r in rows:
        lines += ["== %s   (%d cards, %d columns)" % (r["title"], len(r["LEFT"]), r["columns"]), "   " + r["dsl"], "   card | symbol | column | grid row | role"]
        for i, (kind, text) in enumerate(r["LEFT"]):
            if i in r["placed"]:
                gr, col = r["placed"][i]
                lines.append("   %4d | %-6s | %6d | %8d | %s" % (i + 1, text, col + 1, gr, role(r["FRAC"][i])))
            else:
                lines.append("   %4d | %-6s |      - |        - | %s" % (i + 1, text, role(r["FRAC"][i])))
        lines.append("   bars: " + ", ".join("grid row %d, columns %d-%d" % (b[0], b[1] + 1, b[1] + b[2]) for b in r["bars"]))
        lines.append("")
    open(os.path.join(HERE, "navier_stokes_rows.txt"), "w", encoding="utf-8").write("\n".join(lines))


def write_data(rows):
    """navier_stokes_rows_data.py: the LEFT / LEVELS / FRAC lists of every row, the same fields an operator row file has."""
    out = ['"""Generated by make_navier_stokes_rows.py: the cards of each Navier-Stokes row (same fields as operator_row_math/<operator>/<operator>.py)."""', "", "ROWS = ["]
    for r in rows:
        out += ["    {", "        'title': %r," % r["title"], "        'LEFT': %r," % r["LEFT"], "        'LEVELS': %r," % r["LEVELS"],
                "        'FRAC': %r," % [[list(e) for e in f] for f in r["FRAC"]], "    },"]
    out.append("]")
    open(os.path.join(HERE, "navier_stokes_rows_data.py"), "w", encoding="utf-8").write("\n".join(out) + "\n")


def draw(rows):
    from PIL import Image, ImageDraw, ImageFont
    fonts = os.path.join(os.environ.get("WINDIR", r"C:\Windows"), "Fonts")
    f_card = ImageFont.truetype(os.path.join(fonts, "cambria.ttc"), 24, index=1)
    f_small = ImageFont.truetype(os.path.join(fonts, "segoeui.ttf"), 15)
    f_title = ImageFont.truetype(os.path.join(fonts, "segoeuib.ttf"), 26)
    f_head = ImageFont.truetype(os.path.join(fonts, "segoeuib.ttf"), 17)
    cw, ch, left_pad, top_pad = 40, 40, 150, 14
    ink, line, cell_fill, cell_line = "#1c2b3a", "#dde3ee", "#f7f9fd", "#b9c6dd"
    layout, y = [], 96
    for r in rows:
        grid_rows = [g for g, c in r["placed"].values()] + [b[0] for b in r["bars"]]
        top, bottom = min(grid_rows), max(grid_rows)
        layout.append((y, top, bottom))
        y += 52 + (bottom - top + 1) * ch + 30
    W = left_pad + max(r["columns"] for r in rows) * cw + 40
    img = Image.new("RGB", (W, y + 70), "white")
    d = ImageDraw.Draw(img)
    d.text((40, 20), "Navier\u2013Stokes equations as calculator rows and columns", font=f_title, fill="#16233a")
    d.text((40, 58), "One equation is one row. Every symbol is its own card in its own column; the lines above and below a bar belong to that one row.", font=f_small, fill="#4a5a78")
    d.line((36, 86, W - 36, 86), fill=line, width=2)
    for n, (r, (y0, top, bottom)) in enumerate(zip(rows, layout)):
        d.text((40, y0), "Row %d: %s" % (n + 1, r["title"]), font=f_head, fill="#16233a")
        if n == 0:
            d.text((330, y0), "↓  Rows 2, 3 and 4 are this row written out for the x, y and z directions", font=f_head, fill="#2a6ec9")
        for c in range(r["columns"]):
            d.text((left_pad + c * cw + cw / 2, y0 + 30), str(c + 1), font=f_small, fill="#8a97b0", anchor="mm")
        base = y0 + 40
        for g in range(top, bottom + 1):
            d.text((40, base + (g - top) * ch + ch / 2), "row 0 (the line)" if g == 0 else "row %+d" % g, font=f_small, fill="#8a97b0", anchor="lm")
        for i, (gr, col) in r["placed"].items():
            x, yy = left_pad + col * cw, base + (gr - top) * ch
            d.rounded_rectangle((x + 2, yy + 2, x + cw - 3, yy + ch - 3), radius=6, fill=cell_fill, outline=cell_line)
            d.text((x + cw / 2, yy + ch / 2 + 1), r["LEFT"][i][1], font=f_card, fill=ink, anchor="mm")
        for gr, col, w in r["bars"]:
            yy = base + (gr - top) * ch + ch / 2
            d.line((left_pad + col * cw + 3, yy, left_pad + (col + w) * cw - 3, yy), fill="#2a6ec9", width=3)
        d.line((36, base + (bottom - top + 1) * ch + 12, W - 36, base + (bottom - top + 1) * ch + 12), fill=line, width=2)
    d.text((40, y + 20), "blue line = a fraction bar (the / card is not drawn).   Numerator = the grid row above the bar, denominator = the grid row below it,"
           "   exponent = one grid row up, subscript = one down.", font=f_small, fill="#4a5a78")
    d.text((40, y + 42), "Cards and places come from the project's own row code (see make_navier_stokes_rows.py); the same fields are in navier_stokes_rows_data.py.",
           font=f_small, fill="#4a5a78")
    img.save(os.path.join(HERE, "navier_stokes_rows.jpg"), "JPEG", quality=92)


def preview(rows):
    import tkinter as tk
    from operator_row_math.row_builder import build_row
    root = tk.Tk()
    root.title("Navier-Stokes rows (preview, not in the calculator)")
    for r in rows:
        tk.Label(root, text=r["title"], anchor="w", font=("Segoe UI", 9, "bold")).pack(fill="x", padx=8)
        build_row(root, r["LEFT"], [], False, levels=r["LEVELS"], fracs=r["FRAC"]).pack(anchor="w", padx=8, pady=(0, 10))
    root.mainloop()


if __name__ == "__main__":
    data = build_all()
    if "--preview" in sys.argv:
        preview(data)
    else:
        write_text(data)
        write_data(data)
        draw(data)
        print("wrote navier_stokes_rows.jpg, navier_stokes_rows.txt, navier_stokes_rows_data.py in", HERE)
